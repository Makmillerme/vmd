import sys
from pathlib import Path

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from vmd_extractor.utils.data_extractor import extract_vehicle_type_from_description, extract_body_type_for_cargo_vehicle
import re

# Опис з проблемного автомобіля
description = """1.Моторний колісний транспортний засіб спеціального призначення, призначений для перевезення вантажів по дорогах загального користування, вживаний:
 - марка: VOLKSWAGEN,
 - модель: TRANSPORTER,
 - дата виготовлення кузова: 08.03.2022,
 - модельний рік виготовлення: 2021,
 - календарний рік виготовлення: 2022,
 - VIN/номер кузова: WV1ZZZ7HZNX010323,
 - тип кузова: комбінований кузов,
 - об'єм двигуна: 1968 см3, потужність: 110 кВт,
 - тип палива: дизельне паливо,
 - кількість місць, в т.ч. місць водія: 5,
 - колісна формула: 4x2,
 - вантажопідйомність: 545 кг,
 - маса в разі повного навантаження: 2800 кг,
 - країна походження: Німеччина за кодом країни походження.
Виробник: Volkswagen AG, DE. Торгова марка: "VOLKSWAGEN"."""

print("="*80)
print("АНАЛІЗ ВИЗНАЧЕННЯ ТИПУ АВТОМОБІЛЯ")
print("="*80)
print(f"\nОпис:\n{description}\n")
print("="*80)

# Тестуємо визначення типу
extracted_type = extract_vehicle_type_from_description(description)
print(f"\nВизначений тип: '{extracted_type}'")

# Аналізуємо чому не спрацювало
text = description.strip().lower()
text = re.sub(r'\s+', ' ', text)
text = re.sub(r'^[0-9]+\.?\s*', '', text)

print(f"\n{'='*80}")
print("АНАЛІЗ ПАТТЕРНІВ:")
print(f"{'='*80}")

patterns_to_check = {
    "Сідельний тягач": [
        r'сідельний\s+тягач',
        r'сідельний\s+тягач[аи]',
        r'сідельн[иі]й\s+тягач',
    ],
    "Напівпричіп": [
        r'напівпричіп',
        r'напів\s*причіп',
        r'напів-причіп',
        r'напів\s*прич[іи]п',
    ],
    "Контейнер": [
        r'контейнер\s*\(?\s*змінний\s+кузов\s*\)?',
        r'контейнер\s*\(?\s*змінний\s+кузов',
        r'контейнер\s*\(?\s*змінний',
    ],
    "Автомобіль вантажний": [
        r'автомобіль\s+вантажний',
        r'автомобіль\s+вантажн[иі]й',
        r'вантажний\s+автомобіль',
        r'вантажн[иі]й\s+автомобіль',
    ],
    "Автомобіль легковий": [
        r'автомобіль\s+легковий',
        r'автомобіль\s+легков[иі]й',
        r'легковий\s+автомобіль',
        r'легков[иі]й\s+автомобіль',
    ],
    "Причіп": [
        r'причіп',
        r'прич[іи]п',
    ],
}

for type_name, patterns in patterns_to_check.items():
    found = False
    for pattern in patterns:
        if re.search(pattern, text, re.IGNORECASE):
            found = True
            print(f"  [+] {type_name}: знайдено паттерн '{pattern}'")
            break
    if not found:
        print(f"  [-] {type_name}: не знайдено")

# Перевіряємо ключові фрази
print(f"\n{'='*80}")
print("КЛЮЧОВІ ФРАЗИ В ОПИСІ:")
print(f"{'='*80}")

key_phrases = {
    "Моторний колісний транспортний засіб спеціального призначення": "моторний колісний транспортний засіб спеціального призначення" in text,
    "призначений для перевезення вантажів": "призначений для перевезення вантажів" in text,
    "тип кузова: комбінований кузов": "тип кузова" in text and "комбінований" in text,
    "вантажопідйомність": "вантажопідйомність" in text,
}

for phrase, found in key_phrases.items():
    status = "[+]" if found else "[-]"
    print(f"  {status} {phrase}")

# Перевіряємо чи можна визначити тип кузова
print(f"\n{'='*80}")
print("ВИЗНАЧЕННЯ ТИПУ КУЗОВА:")
print(f"{'='*80}")
body_type = extract_body_type_for_cargo_vehicle(description)
if body_type:
    print(f"  Знайдено тип кузова: '{body_type}'")
else:
    print(f"  Тип кузова не знайдено")
    
    # Перевіряємо чи є "тип кузова" в описі
    body_type_match = re.search(
        r'тип\s+кузова[:\-]?\s*([^,\n\.]+)',
        description,
        re.IGNORECASE
    )
    if body_type_match:
        raw_body_type = body_type_match.group(1).strip()
        print(f"  Але знайдено в описі: 'тип кузова: {raw_body_type}'")

# Висновок
print(f"\n{'='*80}")
print("ВИСНОВОК:")
print(f"{'='*80}")
